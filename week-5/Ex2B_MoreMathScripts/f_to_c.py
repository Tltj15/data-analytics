#1. How do you convert a temperature from Fahrenheit to Celsius?
#c=5/9 (f - 32)
f_temp = 55
celsius = 5/9 * (f_temp - 32)
print(format(celsius, '.2f'), 'celsius')

#2. How do you convert a temperature from Celsius to Fahrenheit?
#f= 9/5 *c + 32
c_temp = 28
f_temp = 9/5 * c_temp + 32
print(f_temp, 'fahrenheit')

